"""Generate docs/reference/configuration.md and docs/reference/cli.md from the code.

Run with `make docs-reference` (or `uv run python scripts/gen_reference.py`) after changing a
setting or a command, so the reference never drifts from the code.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def _comments() -> dict[str, str]:
    """Each setting's comment in prism/config.py: the comment lines just above it, or the
    comment on its own line."""
    import re

    out: dict[str, str] = {}
    above: list[str] = []
    for raw in (ROOT / "prism" / "config.py").read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("#"):
            above.append(line.lstrip("# ").strip())
            continue
        m = re.match(r"(\w+): [^=]+=", line)
        if m:
            inline = line.split("  # ", 1)[1].strip() if "  # " in line else ""
            out[m.group(1)] = " ".join([*above, inline]).strip()
        above = [] if not line.startswith("#") else above
    return out


def configuration() -> str:
    from pydantic import SecretStr

    from prism.config import Settings

    notes = _comments()

    lines = [
        "# Configuration reference",
        "",
        "Every setting is read from the environment or from `.env` in the repo root, with the",
        "`PRISM_` prefix: `review_max_hunks` is `PRISM_REVIEW_MAX_HUNKS`. `.env.example` lists the",
        "ones you are most likely to change. This page is generated from `prism/config.py` by",
        "`make docs-reference`.",
        "",
        "| Variable | Type | Default | Description |",
        "|---|---|---|---|",
    ]
    for name, field in Settings.model_fields.items():
        default = field.default
        if isinstance(default, SecretStr):
            shown = "(secret)" if default.get_secret_value() else '""'
        elif default in ("", None):
            shown = '""' if default == "" else "unset"
        else:
            shown = f"`{default}`"
        kind = getattr(field.annotation, "__name__", str(field.annotation))
        kind = str(kind).replace("typing.", "").replace("|", "or").replace("`", "")
        desc = (field.description or notes.get(name, "")).replace("|", "/")
        lines.append(f"| `PRISM_{name.upper()}` | {kind} | {shown} | {desc} |")
    return "\n".join(lines) + "\n"


def _help(args: list[str]) -> str:
    env = {**os.environ, "COLUMNS": "100", "NO_COLOR": "1", "TERM": "dumb"}
    out = subprocess.run(
        [
            sys.executable,
            "-c",
            "import sys; from prism.cli import app; app(prog_name='prism')",
            *args,
            "--help",
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=env,
        cwd=ROOT,
        check=True,
    ).stdout
    return "\n".join(line.rstrip() for line in out.strip().splitlines())


def cli() -> str:
    from typer.main import get_command

    from prism.cli import app

    root = get_command(app)
    lines = [
        "# CLI reference",
        "",
        "Every `prism` command, as `prism <command> --help` prints it. Generated by",
        "`make docs-reference`.",
        "",
        "```text",
        _help([]),
        "```",
        "",
    ]

    def walk(cmd: object, path: list[str]) -> None:
        subs = getattr(cmd, "commands", None)
        if subs:
            for name in sorted(subs):
                walk(subs[name], [*path, name])
            return
        lines.extend([f"## `prism {' '.join(path)}`", "", "```text", _help(path), "```", ""])

    walk(root, [])
    return "\n".join(lines)


if __name__ == "__main__":
    out = ROOT / "docs" / "reference"
    out.mkdir(parents=True, exist_ok=True)
    (out / "configuration.md").write_text(configuration(), encoding="utf-8", newline="\n")
    (out / "cli.md").write_text(cli(), encoding="utf-8", newline="\n")
    print("wrote docs/reference/configuration.md and docs/reference/cli.md")
